            <h2>7. Cookie について</h2>
            <p>Cookie（ブラウザに一時的に残る小さなデータ）を使っています。</p>
            <ul>
                <li>セッション用の Cookie: 同じ訪問者からのアクセスをつなぐために使います。</li>
                <li>送信フォームの安全のための Cookie（CSRF 用）: 他のサイトからの不正な送信を防ぐために使います。</li>
            </ul>
            <p>セッションの情報は、運営者のデータベースに保存します（4 を参照）。</p>
            <p>ブラウザの設定で Cookie を拒否することもできます。その場合、問い合わせフォームが使えないことがあります。</p>

            <h2>8. 保存期間と削除</h2>
            <ul>
                <li>お預かりした情報（管理画面の記録と、運営者に届いた通知メール）は、ご相談への対応が終わってから1年を目安に削除します。</li>
                <li>運営者は管理画面から、問い合わせを1件ずつ、または複数まとめて削除できます。</li>
                <li>管理画面から削除した情報も、サーバーのバックアップ（毎日1回取っています）には最大14日ほど残り、その後自動で消えます。</li>
                <li>サーバーが壊れたときの備えとして、運営者はときどきバックアップを手元のパソコンに取ります。取るたびに古い写しは自動で消え、手元には最新の1件だけが残ります。そのため、管理画面から削除した情報が、次に写しを取り直すまで、手元の写しに残ることがあります。</li>
                <li>管理画面の記録と通知メールの削除は、運営者が月に1回ほど、まとめて整理して行います。</li>
                <li>セッションと回数制限の記録は、4 に書いたとおり、一定の時間がたつと無効になります。</li>
            </ul>

